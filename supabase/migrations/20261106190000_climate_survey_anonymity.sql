-- A pesquisa de clima promete resposta anônima na interface, mas
-- climate_survey_answers guardava user_id em cada linha -- o anonimato era
-- só uma convenção de query, não uma garantia do banco: qualquer acesso
-- direto (inclusive o dono da conta) conseguia religar resposta -> pessoa.
--
-- Separa a identidade de quem respondeu (climate_survey_responses, usada só
-- pra travar "uma resposta por pessoa por rodada") das notas em si
-- (climate_survey_answers, que passa a não ter mais nenhuma coluna que
-- aponte pra um usuário). As duas tabelas não têm nenhuma chave em comum
-- que permita juntar resposta com pessoa.

CREATE TABLE climate_survey_responses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id bigint NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  round_id bigint NOT NULL,
  user_id bigint NOT NULL,
  responded_at timestamptz NOT NULL DEFAULT NOW(),
  CONSTRAINT climate_responses_round_tenant_fk FOREIGN KEY (round_id, company_id)
    REFERENCES climate_survey_rounds(id, company_id) ON DELETE CASCADE,
  CONSTRAINT climate_responses_user_tenant_fk FOREIGN KEY (user_id, company_id)
    REFERENCES users(id, company_id),
  CONSTRAINT climate_survey_responses_round_id_user_id_key UNIQUE (round_id, user_id)
);

-- Migra o "quem já respondeu" do que já existe antes de remover a coluna.
INSERT INTO climate_survey_responses (company_id, round_id, user_id, responded_at)
SELECT company_id, round_id, user_id, created_at FROM climate_survey_answers;

ALTER TABLE climate_survey_answers DROP CONSTRAINT climate_survey_answers_round_id_user_id_key;
ALTER TABLE climate_survey_answers DROP CONSTRAINT climate_answers_user_tenant_fk;
ALTER TABLE climate_survey_answers DROP COLUMN user_id;

ALTER TABLE climate_survey_responses ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation_select ON climate_survey_responses
  FOR SELECT USING (company_id = private.auth_company_id());
CREATE POLICY tenant_isolation_insert ON climate_survey_responses
  FOR INSERT WITH CHECK (company_id = private.auth_company_id());
